const { test, after } = require('node:test');
const assert = require('node:assert/strict');
const { configured, prisma, fixture, invoke } = require('./integration-fixture.cjs');
const policies = require('../src/app/api/liderazgo/politicas/route.ts');
const submit = require('../src/app/api/liderazgo/politicas/[id]/enviar-revision/route.ts');
const approve = require('../src/app/api/liderazgo/politicas/[id]/aprobar/route.ts');
const adjustments = require('../src/app/api/liderazgo/politicas/[id]/solicitar-ajustes/route.ts');
const communications = require('../src/app/api/liderazgo/politicas/comunicaciones/route.ts');
after(async () => { await prisma.$disconnect(); });

test('5.2: política aislada, revisión, aprobación concurrente, versiones y comunicación verificable', { skip: !configured }, async () => {
  const f = await fixture('policies');
  const body = { tenantId: f.tenant.id, title: 'Política de calidad', content: 'Compromiso de calidad, requisitos y mejora continua.', version: '1.0', type: 'General', objectives: [] };
  let response = await invoke(policies, 'POST', { body });
  assert.equal(response.status, 401);
  response = await invoke(policies, 'POST', { actor: f.auditor, body });
  assert.equal(response.status, 403);
  response = await invoke(policies, 'POST', { actor: f.outsider, body });
  assert.equal(response.status, 403);
  response = await invoke(policies, 'POST', { actor: f.member, body: { ...body, status: 'VIGENTE', author: 'Falso' } });
  assert.equal(response.status, 201, JSON.stringify(response.body));
  let policy = response.body;
  assert.equal(policy.status, 'BORRADOR');
  assert.equal(policy.author, f.member.name);
  const decideBody = () => ({ tenantId: f.tenant.id, expectedUpdatedAt: policy.updatedAt, checks: { context: true, framework: true, requirements: true, improvement: true } });
  response = await invoke(approve, 'POST', { actor: f.admin, body: decideBody(), params: { id: policy.id } });
  assert.equal(response.status, 409);
  response = await invoke(submit, 'POST', { actor: f.member, body: decideBody(), params: { id: policy.id } });
  assert.equal(response.status, 200);
  policy = response.body;
  response = await invoke(policies, 'POST', { actor: f.member, body: { ...body, id: policy.id, expectedUpdatedAt: policy.updatedAt } });
  assert.equal(response.status, 409);
  response = await invoke(approve, 'POST', { actor: f.member, body: decideBody(), params: { id: policy.id } });
  assert.equal(response.status, 403);
  response = await invoke(adjustments, 'POST', { actor: f.admin, body: { ...decideBody(), note: 'Añadir marco de objetivos.' }, params: { id: policy.id } });
  assert.equal(response.status, 200);
  policy = response.body;
  assert.equal(policy.status, 'BORRADOR');
  response = await invoke(policies, 'POST', { actor: f.member, body: { ...body, id: policy.id, content: body.content + ' Marco para objetivos.', expectedUpdatedAt: policy.updatedAt } });
  assert.equal(response.status, 200);
  policy = response.body;
  response = await invoke(submit, 'POST', { actor: f.member, body: decideBody(), params: { id: policy.id } });
  policy = response.body;
  const concurrent = await Promise.all([1, 2].map(() => invoke(approve, 'POST', { actor: f.admin, body: decideBody(), params: { id: policy.id } })));
  assert.deepEqual(concurrent.map(item => item.status).sort(), [200, 409]);
  policy = concurrent.find(item => item.status === 200).body.policy;
  assert.equal(policy.approvalEvents.filter(event => event.action === 'APPROVED').length, 1);
  assert.equal((await invoke(policies, 'POST', { actor: f.member, body: { ...body, type: 'Calidad', version: '2.0' } })).status, 409);
  const unlinked = await prisma.policy.create({ data: {
    tenantId: f.tenant.id, title: 'Borrador sin vínculo anterior', content: 'Prueba',
    type: 'General', version: '1.0', status: 'EN_REVISION', author: f.member.name,
  } });
  assert.equal((await invoke(approve, 'POST', { actor: f.admin, params: { id: unlinked.id },
    body: { ...decideBody(), expectedUpdatedAt: unlinked.updatedAt.toISOString() } })).status, 409);
  assert.equal((await prisma.policy.findUnique({ where: { id: policy.id } })).status, 'VIGENTE');
  const communicationBody = { tenantId: f.tenant.id, policyId: policy.id, audience: 'Equipo', audienceType: 'INTERNA', method: 'Taller', date: '2026-01-02', evidence: 'Acta', understandingEvidence: 'Verificación de aplicación' };
  response = await invoke(communications, 'POST', { actor: f.outsider, body: communicationBody });
  assert.equal(response.status, 403);
  response = await invoke(communications, 'POST', { actor: f.member, body: { ...communicationBody, understandingEvidence: '' } });
  assert.equal(response.status, 400);
  response = await invoke(communications, 'POST', { actor: f.member, body: communicationBody });
  assert.equal(response.status, 201);
  assert.equal(response.body.responsibleName, f.member.name);
  const safety = await prisma.policy.create({ data: { tenantId: f.tenant.id, title: 'Seguridad', type: 'Seguridad', content: 'Seguridad', author: f.admin.name, status: 'VIGENTE' } });
  const previous = policy;
  response = await invoke(policies, 'POST', { actor: f.member, body: { ...body, version: '1.1', supersedesId: previous.id } });
  assert.equal(response.status, 201);
  policy = response.body;
  response = await invoke(submit, 'POST', { actor: f.member, body: decideBody(), params: { id: policy.id } });
  policy = response.body;
  response = await invoke(approve, 'POST', { actor: f.admin, body: decideBody(), params: { id: policy.id } });
  assert.equal(response.status, 200);
  assert.equal((await prisma.policy.findUnique({ where: { id: previous.id } })).status, 'OBSOLETA');
  assert.equal((await prisma.policy.findUnique({ where: { id: safety.id } })).status, 'VIGENTE');
  assert.equal(await prisma.policyCommunication.count({ where: { policyId: previous.id } }), 1);
  assert.equal((await invoke(policies, 'GET', { actor: f.outsider, query: { tenantId: f.tenant.id } })).status, 403);
  assert.equal((await invoke(policies, 'GET', { actor: f.auditor, query: { tenantId: f.tenant.id } })).status, 200);
  assert.equal((await invoke(policies, 'DELETE', { actor: f.admin })).status, 405);
});
