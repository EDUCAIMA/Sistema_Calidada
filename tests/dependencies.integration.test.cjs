/* CommonJS is required by the project's TypeScript test loader. */
const { test, after } = require('node:test');
const assert = require('node:assert/strict');
require('./register.cjs');
const { configured, prisma, fixture, invoke } = require('./integration-fixture.cjs');
const processes = require('../src/app/api/procesos/route.ts');
const users = require('../src/app/api/admin/users/route.ts');
const userRecord = require('../src/app/api/admin/users/[id]/route.ts');

after(async () => { await prisma.$disconnect(); });

test('dependencias: procesos aislados, sin referencias externas ni empresas/usuarios demo', { skip: !configured }, async () => {
  const f = await fixture('dependency-processes');
  const plan = { tenantId: f.tenant.id, name: 'Ventas', code: 'VEN', category: 'MISIONAL', objective: 'Atender clientes', scope: 'Pedidos', responsibleId: f.member.id };
  assert.equal((await invoke(processes, 'GET', { query: { tenantId: f.tenant.id } })).status, 401);
  assert.equal((await invoke(processes, 'GET', { actor: f.outsider, query: { tenantId: f.tenant.id } })).status, 403);
  assert.equal((await invoke(processes, 'POST', { actor: f.auditor, body: plan })).status, 403);
  assert.equal((await invoke(processes, 'POST', { actor: f.member, body: { ...plan, responsibleId: f.outsider.id } })).status, 400);
  const fabricatedUser = 'nonexistent-user-' + f.tenant.id;
  assert.equal((await invoke(processes, 'POST', { actor: f.admin, body: { ...plan, responsibleId: fabricatedUser } })).status, 400);
  assert.equal(await prisma.user.count({ where: { id: fabricatedUser } }), 0);
  const fabricatedTenant = 'nonexistent-tenant-' + f.tenant.id;
  assert.equal((await invoke(processes, 'POST', { actor: f.admin, body: { ...plan, tenantId: fabricatedTenant } })).status, 403);
  assert.equal(await prisma.tenant.count({ where: { id: fabricatedTenant } }), 0);
  const created = await invoke(processes, 'POST', { actor: f.member, body: plan });
  assert.equal(created.status, 201, JSON.stringify(created.body));
  assert.equal(created.body.responsibleName, f.member.name);
  assert.equal((await invoke(processes, 'POST', { actor: f.member, body: plan })).status, 409);
  assert.equal((await invoke(processes, 'POST', { actor: f.outsider, body: { ...plan, id: created.body.id, tenantId: f.otherTenant.id, responsibleId: f.outsider.id } })).status, 404);
  assert.equal((await invoke(processes, 'DELETE', { actor: f.outsider, query: { id: created.body.id } })).status, 404);
  assert.equal((await invoke(processes, 'DELETE', { actor: f.auditor, query: { id: created.body.id } })).status, 403);
  assert.equal((await invoke(processes, 'DELETE', { actor: f.admin, query: { id: created.body.id } })).status, 200);
  const stored = await prisma.process.findUnique({ where: { id: created.body.id } });
  assert.equal(stored.active, false);
  const listed = await invoke(processes, 'GET', { actor: f.member, query: { tenantId: f.tenant.id } });
  assert.equal(listed.body.some((row) => row.id === created.body.id), false);
});

test('dependencias: directorio mínimo, administración autorizada, perfil propio y bloqueo de escalación', { skip: !configured }, async () => {
  const f = await fixture('dependency-users');
  const body = { tenantId: f.tenant.id, name: 'Nueva persona', email: f.tenant.id + '@example.test', role: 'USUARIO', password: 'valid-test-password', position: 'Calidad' };
  assert.equal((await invoke(users, 'GET')).status, 401);
  assert.equal((await invoke(users, 'GET', { actor: f.admin })).status, 403);
  assert.equal((await invoke(users, 'GET', { actor: f.outsider, query: { tenantId: f.tenant.id } })).status, 403);
  const directory = await invoke(users, 'GET', { actor: f.member, query: { tenantId: f.tenant.id } });
  assert.equal(directory.status, 200);
  assert.equal(directory.body.some((user) => user.id === f.member.id), true);
  assert.equal(directory.body.every((user) => !('password' in user) && !('phone' in user) && !('email' in user)), true);
  assert.equal((await invoke(users, 'POST', { actor: f.member, body })).status, 403);
  assert.equal((await invoke(users, 'POST', { actor: f.admin, body: { ...body, role: 'SUPER_ADMIN' } })).status, 403);
  assert.equal((await invoke(users, 'POST', { actor: f.admin, body: { ...body, tenantId: f.otherTenant.id } })).status, 403);
  const created = await invoke(users, 'POST', { actor: f.admin, body });
  assert.equal(created.status, 201, JSON.stringify(created.body));
  assert.equal('password' in created.body, false);
  const id = created.body.id;
  assert.equal((await invoke(userRecord, 'GET', { actor: f.outsider, params: { id } })).status, 404);
  assert.equal((await invoke(userRecord, 'GET', { actor: f.member, params: { id } })).status, 403);
  assert.equal((await invoke(userRecord, 'PATCH', { actor: f.member, params: { id }, body: { name: 'Alterado' } })).status, 403);
  assert.equal((await invoke(userRecord, 'PATCH', { actor: f.member, params: { id: f.member.id }, body: { role: 'SUPER_ADMIN' } })).status, 400);
  const self = await invoke(userRecord, 'PATCH', { actor: f.member, params: { id: f.member.id }, body: { name: 'Responsable actualizado', position: 'Calidad', phone: '123' } });
  assert.equal(self.status, 200);
  assert.equal(self.body.role, 'USUARIO');
  assert.equal('password' in self.body, false);
  assert.equal((await invoke(userRecord, 'PATCH', { actor: f.admin, params: { id }, body: { role: 'SUPER_ADMIN' } })).status, 403);
  assert.equal((await invoke(userRecord, 'PATCH', { actor: f.admin, params: { id }, body: { tenantId: f.otherTenant.id } })).status, 403);
  assert.equal((await invoke(userRecord, 'DELETE', { actor: f.member, params: { id } })).status, 403);
  assert.equal((await invoke(userRecord, 'DELETE', { actor: f.admin, params: { id } })).status, 200);
  assert.equal((await prisma.user.findUnique({ where: { id } })).active, false);
  const after = await invoke(users, 'GET', { actor: f.auditor, query: { tenantId: f.tenant.id } });
  assert.equal(after.body.some((user) => user.id === id), false);
  const superAdmin = await prisma.user.create({ data: { tenantId: f.tenant.id, name: 'Administrador global', email: 'super-' + f.tenant.id + '@example.test', role: 'SUPER_ADMIN' } });
  const global = await invoke(users, 'GET', { actor: superAdmin });
  assert.equal(global.status, 200);
  assert.equal(global.body.every((user) => !('password' in user)), true);
  assert.equal((await invoke(userRecord, 'PATCH', { actor: f.admin, params: { id: superAdmin.id }, body: { password: 'test-password' } })).status, 403);
  assert.equal((await invoke(userRecord, 'PATCH', { actor: superAdmin, params: { id: f.member.id }, body: { tenantId: f.otherTenant.id } })).status, 409);
});

test('dependencias: listado de gestión restringido permite editar, desactivar y reactivar usuarios reales', { skip: !configured }, async () => {
  const f = await fixture('dependency-user-management');
  const query = { tenantId: f.tenant.id, manage: 'true' };
  assert.equal((await invoke(users, 'GET', { query })).status, 401);
  assert.equal((await invoke(users, 'GET', { actor: f.member, query })).status, 403);
  assert.equal((await invoke(users, 'GET', { actor: f.auditor, query })).status, 403);
  assert.equal((await invoke(users, 'GET', { actor: f.outsider, query })).status, 403);
  assert.equal((await invoke(users, 'GET', { actor: f.admin, query: { manage: 'true' } })).status, 400);
  const created = await invoke(users, 'POST', { actor: f.admin, body: { tenantId: f.tenant.id, name: 'Persona gestionada', email: f.tenant.id + '-managed@example.test', role: 'USUARIO', position: 'Analista', password: 'test-password-123' } });
  assert.equal(created.status, 201);
  const id = created.body.id;
  const changed = await invoke(userRecord, 'PATCH', { actor: f.admin, params: { id }, body: { role: 'AUDITOR_EXTERNO', position: 'Auditor de calidad' } });
  assert.equal(changed.status, 200);
  assert.equal(changed.body.role, 'AUDITOR_EXTERNO');
  assert.equal(changed.body.position, 'Auditor de calidad');
  assert.equal((await invoke(userRecord, 'DELETE', { actor: f.admin, params: { id } })).status, 200);
  const managed = await invoke(users, 'GET', { actor: f.admin, query });
  assert.equal(managed.status, 200);
  const saved = managed.body.find(row => row.id === id);
  assert.equal(saved.active, false);
  assert.equal(saved.email, created.body.email);
  assert.equal(saved.position, 'Auditor de calidad');
  assert.ok(managed.body.every(row => row.tenantId === f.tenant.id && !('password' in row) && !('phone' in row)));
  const directory = await invoke(users, 'GET', { actor: f.member, query: { tenantId: f.tenant.id } });
  assert.ok(directory.body.every(row => row.active && !('email' in row)));
  assert.equal(directory.body.some(row => row.id === id), false);
  assert.equal((await invoke(userRecord, 'PATCH', { actor: f.admin, params: { id }, body: { active: true } })).status, 200);
  const restored = await invoke(users, 'GET', { actor: f.admin, query });
  assert.equal(restored.body.find(row => row.id === id).active, true);
  assert.equal((await invoke(userRecord, 'DELETE', { actor: f.admin, params: { id: f.admin.id } })).status, 409);
});
